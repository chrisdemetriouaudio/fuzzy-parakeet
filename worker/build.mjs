// Runs before every `wrangler dev` and `wrangler deploy` (see wrangler.jsonc), and before
// the tests. It hashes each inline <script> on the published pages, so the CSP allows
// exactly the site's own scripts. Change an inline script and its hash changes with it.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { ROOT, publishedFiles, inlineScripts } from "./site-files.mjs";

const hashes = new Set();
for (const file of publishedFiles().filter((f) => f.endsWith(".html"))) {
  for (const code of inlineScripts(readFileSync(join(ROOT, file), "utf8"))) {
    hashes.add(createHash("sha256").update(code, "utf8").digest("base64"));
  }
}
const list = [...hashes].sort();
writeFileSync(
  join(ROOT, "worker/csp-hashes.js"),
  "// Generated by worker/build.mjs. Do not edit; it's rebuilt before every dev and deploy.\n" +
    `export const SCRIPT_HASHES = ${JSON.stringify(list, null, 2)};\n`,
);
console.log(`worker/build.mjs: ${list.length} inline script hashes`);
